export async function migrateTenant(db: Db): Promise<string[]> {
  await db.execute(`CREATE TABLE IF NOT EXISTS _migrations (id TEXT PRIMARY KEY, "appliedAt" TIMESTAMPTZ DEFAULT now())`)
  const done = new Set((await db.execute('SELECT id FROM _migrations')).rows.map((r) => String(r.id)))
  const applied: string[] = []
  for (const m of MIGRATIONS) {
    if (done.has(m.id)) continue
    // Transacción: si algo falla a mitad, no queda el esquema a medias.
    await db.batch([...m.sql, { sql: 'INSERT INTO _migrations (id) VALUES (?)', args: [m.id] }])
    applied.push(m.id)
  }
  return applied
}

